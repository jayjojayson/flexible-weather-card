const fs = require('fs');
const path = require('path');

// Quellteile in src/ werden in dieser Reihenfolge zu dist/flexible-weather-card.js gebündelt.
// (Die Reihenfolge ist wichtig: Core -> Elemente -> Card -> Editor -> Designer)
const SRC_DIR = 'src';
const DIST_DIR = 'dist';
const OUTPUT_FILE = path.join(DIST_DIR, 'flexible-weather-card.js');
const PARTS = [
  'fwc-core.js',
  'fwc-earth.js',
  'fwc-elements.js',
  'flexible-weather-card.js',
  'flexible-weather-card-editor.js',
  'flexible-weather-card-designer.js',
];

if (!fs.existsSync(DIST_DIR)) fs.mkdirSync(DIST_DIR);

// Lit-Deklarationen gibt es nur einmal (im Core); falls ein Teil sie selbst mitbringt, werden sie entfernt
const LIT_DECL = /const LitElement = customElements\.get\("ha-lit-element"\).*;\s*const html = LitElement\.prototype\.html;\s*const css = LitElement\.prototype\.css;\s*/;

const chunks = PARTS.map((file, i) => {
  const p = path.join(SRC_DIR, file);
  if (!fs.existsSync(p)) throw new Error(`Missing source part: ${p}`);
  let content = fs.readFileSync(p, 'utf8');
  if (i > 0) content = content.replace(LIT_DECL, '');
  console.log(`+ ${file}`);
  return `// ===== ${file} =====\n${content.trim()}\n`;
});

const finalContent = `/**
 * Flexible Weather Card (Bundled)
 * Generated by build.js – do not edit, change the files in src/ instead.
 * Source: ${PARTS.map(p => `src/${p}`).join(', ')}
 */

${chunks.join('\n')}`;

fs.writeFileSync(OUTPUT_FILE, finalContent);
console.log(`Build complete: ${OUTPUT_FILE} (${Math.round(finalContent.length / 1024)} KB)`);
